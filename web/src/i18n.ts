export function detectLang(): Lang {
  const saved = localStorage.getItem("usagehub.lang");
  if (saved === "en" || saved === "zh") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setLang(lang: Lang) {
  localStorage.setItem("usagehub.lang", lang);
}

export function useLang(): Lang {
  const [lang, setLangState] = useState<Lang>(() => detectLang());
  useEffect(() => {
    function onStorage(event: StorageEvent) {
      if (event.key === "usagehub.lang" && (event.newValue === "en" || event.newValue === "zh")) {
        setLangState(event.newValue as Lang);
      }
    }
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);
  return lang;
}

export type Messages = Record<keyof typeof messages.en, string>;

export function tpl(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    String(values[key] ?? ""),
  );
}
